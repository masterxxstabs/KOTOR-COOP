//! Wire protocol for KOTOR Co-op.
//!
//! Every message travels over a single TCP stream as a frame:
//!
//! ```text
//! +----------------+---------------------------+
//! | u32 LE length  | postcard-encoded payload  |
//! +----------------+---------------------------+
//! ```
//!
//! The payload is either a [`ClientMessage`] (client -> server) or a
//! [`ServerMessage`] (server -> client). Bump [`PROTOCOL_VERSION`] whenever a
//! change breaks compatibility; the server rejects mismatched clients during
//! the handshake so players get a clear "please update" message from the
//! launcher instead of a desync.

pub mod client;
mod frame;
pub mod master;
mod types;

pub use frame::{decode_payload, encode_frame, FrameDecoder, FrameError, MAX_FRAME_LEN};
pub use types::*;

use serde::{Deserialize, Serialize};

/// Incremented on any breaking change to the messages below.
pub const PROTOCOL_VERSION: u32 = 1;

/// Default TCP port of a dedicated server.
pub const DEFAULT_PORT: u16 = 27700;

/// Default port of the master server (server browser + update host).
pub const DEFAULT_MASTER_PORT: u16 = 27780;

/// Version of this co-op mod build; reported in the handshake and to the master list.
pub const MOD_VERSION: &str = env!("CARGO_PKG_VERSION");

/// Messages sent by a game client (the injected DLL) or a tool.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub enum ClientMessage {
    /// First message on every connection.
    Hello(Hello),
    /// Latency probe; the server echoes the value back in [`ServerMessage::Pong`].
    Ping { nonce: u64 },
    /// Periodic (~20 Hz) update of the local player's character.
    PlayerState(PlayerState),
    /// The local player finished loading into a module.
    EnteredModule { module: ModuleName },
    /// The party leader asks everyone to travel to another module.
    RequestTransition {
        module: ModuleName,
        waypoint: String,
    },
    /// A plot/quest global changed locally (GLOBALVARS.res).
    SetGlobal { name: String, value: GlobalValue },
    /// Something persistent happened inside a module (NPC died, chest looted, ...).
    WorldEvent(WorldEvent),
    /// Conversation sync: the client started, advanced or left a dialog.
    Dialog(DialogEvent),
    /// Text chat.
    Chat { text: String },
    /// Serialized character (stats, inventory, ...) for server-side persistence.
    SaveCharacter { data: Vec<u8> },
    /// Graceful disconnect.
    Goodbye,
}

/// Messages sent by the dedicated server.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub enum ServerMessage {
    /// Handshake accepted.
    Welcome(Welcome),
    /// Handshake refused; the connection is closed afterwards.
    Rejected {
        reason: RejectReason,
        message: String,
    },
    Pong {
        nonce: u64,
    },
    PlayerJoined(PlayerInfo),
    PlayerLeft {
        id: PlayerId,
    },
    /// Batched states of other players (the receiver's own state is omitted).
    PlayerStates(Vec<(PlayerId, PlayerState)>),
    /// A new party leader was chosen.
    LeaderChanged {
        id: PlayerId,
    },
    /// Everyone should travel to this module (sent when the leader transitions).
    Transition {
        module: ModuleName,
        waypoint: String,
    },
    GlobalChanged {
        name: String,
        value: GlobalValue,
    },
    WorldEvent {
        from: PlayerId,
        event: WorldEvent,
    },
    Dialog {
        from: PlayerId,
        event: DialogEvent,
    },
    Chat {
        from: Option<PlayerId>,
        name: String,
        text: String,
    },
    /// Character data stored on the server for this player (sent on join).
    CharacterData {
        data: Vec<u8>,
    },
    /// Server is going away (restart/shutdown).
    Shutdown {
        message: String,
    },
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Hello {
    pub protocol_version: u32,
    /// Version of the co-op mod package the client is running (from the launcher manifest).
    pub mod_version: String,
    pub player_name: String,
    /// Random secret generated by the launcher on first run. Binds a player name
    /// to one person so nobody else can join as them and take their character.
    pub player_token: String,
    pub password: Option<String>,
    /// SHA-256 of swkotor.exe, so the server can log which game builds connect.
    pub game_build: Option<String>,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Welcome {
    pub your_id: PlayerId,
    pub server_name: String,
    pub motd: String,
    pub leader: Option<PlayerId>,
    pub players: Vec<PlayerInfo>,
    pub world: WorldSnapshot,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum RejectReason {
    VersionMismatch,
    BadPassword,
    ServerFull,
    NameTaken,
    InvalidName,
    Banned,
    ProtocolError,
}
